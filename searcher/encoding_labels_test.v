fn test_encoding_rs_replacement_labels_are_rejected() {
	for label in [
		'hz-gb-2312',
		'iso-2022-cn',
		'iso-2022-kr',
		'csiso2022kr',
		'replacement',
		'iso-2022-cn-ext',
	] {
		if _ := Encoding.new(label) {
			panic('accepted encoding_rs replacement label `${label}`')
		}
	}
}
