fn parse_unicode_class_set_expression(pattern string, start int, end int, config Config) ([]UnicodeRange, bool, int) {
	mut i := start
	mut negated := false
	if i < end && pattern[i] == `^` {
		negated = true
		i++
	}
	mut ranges, ok, next := parse_unicode_class_union_until_operation(pattern, i, end,
		config)
	if !ok {
		return ranges, false, next
	}
	i = next
	for i < end {
		if i + 1 >= end {
			return ranges, false, i
		}
		op := pattern[i..i + 2]
		if op !in ['&&', '--', '~~'] {
			return ranges, false, i
		}
		right, right_ok, right_next := parse_unicode_class_union_until_operation(pattern,
			i + 2, end, config)
		if !right_ok {
			return ranges, false, right_next
		}
		ranges = match op {
			'&&' { intersect_unicode_ranges(ranges, right) }
			'--' { subtract_unicode_ranges(ranges, right) }
			'~~' { symmetric_difference_unicode_ranges(ranges, right) }
			else { ranges }
		}
		i = right_next
	}
	if negated {
		ranges = complement_unicode_ranges(ranges)
	}
	return ranges, true, i
}

fn parse_unicode_class_union_until_operation(pattern string, start int, end int, config Config) ([]UnicodeRange, bool, int) {
	mut i := start
	mut ranges := []UnicodeRange{}
	mut saw_atom := false
	for i < end {
		if i + 1 < end && pattern[i..i + 2] in ['&&', '--', '~~'] {
			break
		}
		start_atom, next_i := parse_unicode_class_atom(pattern, i, end, config)
		i = next_i
		if !start_atom.ok {
			return ranges, false, i
		}
		saw_atom = true
		if i + 1 < end && pattern[i] == `-` && pattern[i + 1] != `-` {
			i++
			end_atom, after_end := parse_unicode_class_atom(pattern, i, end, config)
			i = after_end
			if !end_atom.ok || !start_atom.has_single || !end_atom.has_single {
				return ranges, false, i
			}
			first := if start_atom.single < end_atom.single { start_atom.single } else { end_atom.single }
			last := if start_atom.single < end_atom.single { end_atom.single } else { start_atom.single }
			ranges = union_unicode_ranges(ranges, [UnicodeRange{first, last}])
		} else {
			ranges = union_unicode_ranges(ranges, start_atom.ranges)
		}
	}
	return ranges, saw_atom, i
}

fn parse_unicode_class_atom(pattern string, i int, end int, config Config) (UnicodeClassAtom, int) {
	if i >= end {
		return UnicodeClassAtom{}, i
	}
	if pattern[i] == `[` {
		if i + 3 < pattern.len && pattern[i + 1] == `:` {
			mut pos := i + 2
			mut negated := false
			if pos < pattern.len && pattern[pos] == `^` {
				negated = true
				pos++
			}
			name_start := pos
			for pos + 1 < pattern.len && !(pattern[pos] == `:` && pattern[pos + 1] == `]`) {
				pos++
			}
			if pos + 1 < pattern.len {
				mut ranges := posix_class_ranges(pattern[name_start..pos]) or {
					return UnicodeClassAtom{}, pos + 2
				}
				if negated {
					ranges = complement_unicode_ranges(ranges)
				}
				return UnicodeClassAtom{
					ranges: ranges
					ok:     true
				}, pos + 2
			}
		}
		nested_end := find_class_end_nested(pattern, i) or { return UnicodeClassAtom{}, end }
		nested, ok, next := parse_unicode_class_set_expression(pattern, i + 1, nested_end,
			config)
		return UnicodeClassAtom{
			ranges: nested
			ok:     ok && next == nested_end
		}, nested_end + 1
	}
	if pattern[i] == `\\` {
		return parse_unicode_escape_class(pattern, i, end, config)
	}
	value, width := read_pattern_rune_at(pattern, i)
	if width == 0 {
		return UnicodeClassAtom{}, end
	}
	return UnicodeClassAtom{
		ranges:     [UnicodeRange{value, value}]
		single:     value
		has_single: true
		ok:         true
	}, i + width
}

fn parse_unicode_escape_class(pattern string, i int, end int, config Config) (UnicodeClassAtom, int) {
	if i + 1 >= end {
		return UnicodeClassAtom{}, end
	}
	next := pattern[i + 1]
	if next == `p` || next == `P` {
		escape := rust_property_escape_at(pattern, i) or { return UnicodeClassAtom{}, skip_regex_escape(pattern, i) }
		if escape.next > end {
			return UnicodeClassAtom{}, end
		}
		encoded := rust_property_class_encoded(escape.property, config) or {
			return UnicodeClassAtom{}, escape.next
		}
		mut ranges := unicode_ranges_from_encoded(encoded)
		if next == `P` {
			ranges = complement_unicode_ranges(ranges)
		}
		return UnicodeClassAtom{
			ranges: ranges
			ok:     true
		}, escape.next
	}
	mut ranges := []UnicodeRange{}
	match next {
		`w`, `W` {
			ranges = if config.unicode {
				unicode_ranges_from_encoded(generated_unicode_word_encoded())
			} else {
				[UnicodeRange{`0`, `9`}, UnicodeRange{`A`, `Z`}, UnicodeRange{`_`, `_`},
					UnicodeRange{`a`, `z`}]
			}
			if next == `W` {
				ranges = complement_unicode_ranges(ranges)
			}
			return UnicodeClassAtom{
				ranges: ranges
				ok:     true
			}, i + 2
		}
		`d`, `D` {
			ranges = if config.unicode {
				unicode_ranges_from_encoded(generated_unicode_property_encoded('gc=Decimal_Number') or {
					return UnicodeClassAtom{}, i + 2
				})
			} else {
				[UnicodeRange{`0`, `9`}]
			}
			if next == `D` {
				ranges = complement_unicode_ranges(ranges)
			}
			return UnicodeClassAtom{
				ranges: ranges
				ok:     true
			}, i + 2
		}
		`s`, `S` {
			ranges = if config.unicode { whitespace_ranges() } else {
				[UnicodeRange{`\t`, `\t`}, UnicodeRange{`\n`, `\n`}, UnicodeRange{rune(0x0b), rune(0x0c)},
					UnicodeRange{`\r`, `\r`}, UnicodeRange{` `, ` `}]
			}
			if next == `S` {
				ranges = complement_unicode_ranges(ranges)
			}
			return UnicodeClassAtom{
				ranges: ranges
				ok:     true
			}, i + 2
		}
		else {}
	}
	if escape := rust_unicode_escape_at(pattern, i) {
		value := rune(escape.codepoint)
		return UnicodeClassAtom{
			ranges:     [UnicodeRange{value, value}]
			single:     value
			has_single: true
			ok:         true
		}, escape.next
	}
	has_byte, byte, next_i := parse_escape_byte(pattern, i)
	if !has_byte || next_i > end {
		return UnicodeClassAtom{}, if next_i > end { end } else { next_i }
	}
	value := rune(byte)
	return UnicodeClassAtom{
		ranges:     [UnicodeRange{value, value}]
		single:     value
		has_single: true
		ok:         true
	}, next_i
}

fn read_pattern_rune_at(pattern string, index int) (rune, int) {
	if index >= pattern.len {
		return rune(0), 0
	}
	b0 := u32(pattern[index])
	if b0 < 0x80 {
		return rune(b0), 1
	}
	if (b0 & 0xe0) == 0xc0 && index + 1 < pattern.len {
		return rune(((b0 & 0x1f) << 6) | (u32(pattern[index + 1]) & 0x3f)), 2
	}
	if (b0 & 0xf0) == 0xe0 && index + 2 < pattern.len {
		return rune(((b0 & 0x0f) << 12) | ((u32(pattern[index + 1]) & 0x3f) << 6) |
			(u32(pattern[index + 2]) & 0x3f)), 3
	}
	if (b0 & 0xf8) == 0xf0 && index + 3 < pattern.len {
		return rune(((b0 & 0x07) << 18) | ((u32(pattern[index + 1]) & 0x3f) << 12) |
			((u32(pattern[index + 2]) & 0x3f) << 6) | (u32(pattern[index + 3]) & 0x3f)), 4
	}
	return rune(0), 0
}

fn normalize_property_class_at(pattern string, start int, config Config) ?PatternReplacement {
	if start >= pattern.len || pattern[start] != `[` {
		return none
	}
	end := find_class_end_nested(pattern, start) or { return none }
	body := pattern[start + 1..end]
	if !body.contains(r'\p') && !body.contains(r'\P') {
		return none
	}
	mut out := []u8{cap: body.len}
	mut i := start + 1
	mut outer_negated := false
	if i < end && pattern[i] == `^` {
		outer_negated = true
		i++
	}
	if i < end && pattern[i] == `\\` && i + 1 < end
		&& (pattern[i + 1] == `p` || pattern[i + 1] == `P`) {
		property_escape := rust_property_escape_at(pattern, i) or { return none }
		if property_escape.next == end {
			body_part := rust_property_class_body(property_escape.property, config) or { return none }
			property_negated := pattern[i + 1] == `P`
			text := if property_negated != outer_negated {
				negated_backend_class(body_part, config)
			} else {
				'[${body_part}]'
			}
			return PatternReplacement{
				text: text
				next: end + 1
			}
		}
	}
	out << `[`
	if outer_negated {
		out << `^`
	}
	for i < end {
		if pattern[i] == `\\` && i + 1 < end {
			next := pattern[i + 1]
			if next == `p` || next == `P` {
				property_escape := rust_property_escape_at(pattern, i) or { return none }
				if property_escape.next > end {
					return none
				}
				if next == `P` {
					return none
				}
				body_part := rust_property_class_body(property_escape.property, config) or { return none }
				out << body_part.bytes()
				i = property_escape.next
				continue
			}
			out << pattern[i]
			out << next
			i += 2
			continue
		}
		out << pattern[i]
		i++
	}
	out << `]`
	return PatternReplacement{
		text: out.bytestr()
		next: end + 1
	}
}

fn find_class_end_nested(pattern string, start int) ?int {
	if start >= pattern.len || pattern[start] != `[` {
		return none
	}
	mut i := start + 1
	if i < pattern.len && pattern[i] == `^` {
		i++
	}
	if i < pattern.len && pattern[i] == `]` {
		i++
	}
	for i < pattern.len {
		if pattern[i] == `\\` {
			i = skip_regex_escape(pattern, i)
			continue
		}
		if i + 1 < pattern.len && pattern[i] == `[` && pattern[i + 1] == `:` {
			mut posix_end := i + 2
			for posix_end + 1 < pattern.len {
				if pattern[posix_end] == `:` && pattern[posix_end + 1] == `]` {
					i = posix_end + 2
					break
				}
				posix_end++
			}
			if posix_end + 1 >= pattern.len {
				return none
			}
			continue
		}
		if pattern[i] == `[` {
			nested_end := find_class_end_nested(pattern, i) or { return none }
			i = nested_end + 1
			continue
		}
		if pattern[i] == `]` {
			return i
		}
		i++
	}
	return none
}

fn skip_regex_escape(pattern string, start int) int {
	if start + 1 >= pattern.len {
		return pattern.len
	}
	next := pattern[start + 1]
	if next in [`p`, `P`, `u`] && start + 2 < pattern.len && pattern[start + 2] == `{` {
		mut i := start + 3
		for i < pattern.len && pattern[i] != `}` {
			i++
		}
		if i < pattern.len {
			return i + 1
		}
	}
	if next == `u` && start + 6 <= pattern.len {
		return start + 6
	}
	if next == `U` && start + 10 <= pattern.len {
		return start + 10
	}
	return start + 2
}

fn parse_class_set_expression(pattern string, start int, end int) ([]bool, bool, int) {
	mut i := start
	mut negated := false
	if i < end && pattern[i] == `^` {
		negated = true
		i++
	}
	mut set, ok, next := parse_class_union_until_operation(pattern, i, end)
	if !ok {
		return set, false, next
	}
	i = next
	for i < end {
		if i + 1 >= end {
			return set, false, i
		}
		op := pattern[i..i + 2]
		if op != '&&' && op != '--' && op != '~~' {
			return set, false, i
		}
		right, right_ok, right_next := parse_class_union_until_operation(pattern, i + 2, end)
		if !right_ok {
			return set, false, right_next
		}
		apply_class_set_operation(mut set, right, op)
		i = right_next
	}
	if negated {
		invert_byte_class(mut set)
	}
	return set, true, i
}

fn parse_class_union_until_operation(pattern string, start int, end int) ([]bool, bool, int) {
	mut i := start
	mut set := empty_byte_class()
	mut saw_atom := false
	for i < end {
		if i + 1 < end && ((pattern[i] == `&` && pattern[i + 1] == `&`)
			|| (pattern[i] == `-` && pattern[i + 1] == `-`) || (pattern[i] == `~`
			&& pattern[i + 1] == `~`)) {
			break
		}
		start_atom, next_i := parse_class_atom_bounded(pattern, i, end)
		i = next_i
		if !start_atom.ok {
			return set, false, i
		}
		saw_atom = true
		if i < end && pattern[i] == `-` && !(i + 1 < end && pattern[i + 1] == `-`) {
			i++
			end_atom, after_end := parse_class_atom_bounded(pattern, i, end)
			i = after_end
			if !end_atom.ok {
				return set, false, i
			}
			if start_atom.has_single && end_atom.has_single {
				add_byte_range(mut set, start_atom.single, end_atom.single)
			} else {
				add_byte_class(mut set, start_atom.set)
				add_byte_class(mut set, end_atom.set)
			}
		} else {
			add_byte_class(mut set, start_atom.set)
		}
	}
	return set, saw_atom, i
}

fn parse_class_atom_bounded(pattern string, i int, end int) (ClassAtom, int) {
	if i >= end {
		return ClassAtom{}, i
	}
	if pattern[i] == `[` {
		if i + 11 <= pattern.len && pattern[i..i + 11] == '[[:alpha:]]' {
			mut set := empty_byte_class()
			add_byte_range(mut set, `A`, `Z`)
			add_byte_range(mut set, `a`, `z`)
			return ClassAtom{
				set: set
				ok:  true
			}, i + 11
		}
		nested_end := find_class_end_nested(pattern, i) or { return ClassAtom{}, end }
		nested, ok, next := parse_class_set_expression(pattern, i + 1, nested_end)
		if !ok || next != nested_end {
			return ClassAtom{}, nested_end + 1
		}
		return ClassAtom{
			set: nested
			ok:  true
		}, nested_end + 1
	}
	if pattern[i] == `\\` {
		set, has_single, single, ok, next := parse_escape_class(pattern, i)
		if next > end {
			return ClassAtom{}, end
		}
		return ClassAtom{
			set:        set
			single:     single
			has_single: has_single
			ok:         ok
		}, next
	}
	byte := pattern[i]
	mut set := empty_byte_class()
	set[int(byte)] = true
	return ClassAtom{
		set:        set
		single:     byte
		has_single: true
		ok:         true
	}, i + 1
}

fn apply_class_set_operation(mut set []bool, right []bool, op string) {
	for i, present in right {
		match op {
			'&&' {
				set[i] = set[i] && present
			}
			'--' {
				if present {
					set[i] = false
				}
			}
			'~~' {
				set[i] = set[i] != present
			}
			else {}
		}
	}
}

fn parse_class_set(pattern string, start int) ([]bool, bool, int) {
	mut i := start
	mut negated := false
	if i < pattern.len && pattern[i] == `^` {
		negated = true
		i++
	}
	mut set := empty_byte_class()
	for i < pattern.len {
		if pattern[i] == `]` {
			i++
			if negated {
				invert_byte_class(mut set)
			}
			return set, true, i
		}
		start_atom, next_i := parse_class_atom(pattern, i)
		i = next_i
		if !start_atom.ok {
			return set, false, i
		}
		if i < pattern.len && pattern[i] == `-` && i + 1 < pattern.len && pattern[i + 1] != `]` {
			i++
			end_atom, after_end := parse_class_atom(pattern, i)
			i = after_end
			if !end_atom.ok {
				return set, false, i
			}
			if start_atom.has_single && end_atom.has_single {
				add_byte_range(mut set, start_atom.single, end_atom.single)
			} else {
				add_byte_class(mut set, start_atom.set)
				add_byte_class(mut set, end_atom.set)
			}
		} else {
			add_byte_class(mut set, start_atom.set)
		}
	}
	return set, false, i
}

fn parse_class_atom(pattern string, i int) (ClassAtom, int) {
	if i >= pattern.len {
		return ClassAtom{}, i
	}
	if pattern[i] == `[` {
		nested, ok, next := parse_class_set(pattern, i + 1)
		return ClassAtom{
			set: nested
			ok:  ok
		}, next
	}
	if pattern[i] == `\\` {
		set, has_single, single, ok, next := parse_escape_class(pattern, i)
		return ClassAtom{
			set:        set
			single:     single
			has_single: has_single
			ok:         ok
		}, next
	}
	byte := pattern[i]
	mut set := empty_byte_class()
	set[int(byte)] = true
	return ClassAtom{
		set:        set
		single:     byte
		has_single: true
		ok:         true
	}, i + 1
}

fn parse_escape_class(pattern string, i int) ([]bool, bool, u8, bool, int) {
	if i + 1 >= pattern.len {
		return full_byte_class(), false, u8(0), false, pattern.len
	}
	next := pattern[i + 1]
	match next {
		`d` {
			mut set := empty_byte_class()
			add_byte_range(mut set, `0`, `9`)
			return set, false, u8(0), true, i + 2
		}
		`D` {
			mut set := full_byte_class()
			for byte := `0`; byte <= `9`; byte++ {
				set[int(byte)] = false
			}
			return set, false, u8(0), true, i + 2
		}
		`s` {
			mut set := empty_byte_class()
			for byte in [`\t`, `\n`, 0x0b, 0x0c, `\r`, ` `] {
				set[int(byte)] = true
			}
			return set, false, u8(0), true, i + 2
		}
		`S` {
			mut set := full_byte_class()
			for byte in [`\t`, `\n`, 0x0b, 0x0c, `\r`, ` `] {
				set[int(byte)] = false
			}
			return set, false, u8(0), true, i + 2
		}
		`w` {
			mut set := empty_byte_class()
			add_word_bytes(mut set)
			return set, false, u8(0), true, i + 2
		}
		`W` {
			mut set := full_byte_class()
			mut word := empty_byte_class()
			add_word_bytes(mut word)
			for index, present in word {
				if present {
					set[index] = false
				}
			}
			return set, false, u8(0), true, i + 2
		}
		`p`, `P` {
			if end := rust_property_escape_end(pattern, i) {
				property := pattern[i + 3..int(end) - 1]
				if mut set := rust_property_byte_class(property) {
					if next == `P` {
						invert_byte_class(mut set)
					}
					return set, false, u8(0), true, int(end)
				}
			} else if i + 3 <= pattern.len && pattern[i..i + 3] == r'\pL' {
				mut set := empty_byte_class()
				add_byte_range(mut set, `A`, `Z`)
				add_byte_range(mut set, `a`, `z`)
				return set, false, u8(0), true, i + 3
			}
			return full_byte_class(), false, u8(0), false, skip_regex_escape(pattern, i)
		}
		else {
			has_byte, byte, next_i := parse_escape_byte(pattern, i)
			if !has_byte {
				return full_byte_class(), false, u8(0), true, next_i
			}
			mut set := empty_byte_class()
			set[int(byte)] = true
			return set, true, byte, true, next_i
		}
	}
}

fn parse_escape_byte(pattern string, i int) (bool, u8, int) {
	if i + 1 >= pattern.len {
		return false, u8(0), pattern.len
	}
	next := pattern[i + 1]
	if escaped := escaped_byte(next) {
		return true, escaped, i + 2
	}
	if next == `x` {
		if i + 2 < pattern.len && pattern[i + 2] == `{` {
			mut end := i + 3
			for end < pattern.len && pattern[end] != `}` {
				end++
			}
			if end < pattern.len {
				value := parse_hex_u32(pattern[i + 3..end]) or { return false, u8(0), end + 1 }
				if value <= 0xff {
					return true, u8(value), end + 1
				}
				return false, u8(0), end + 1
			}
		}
		if i + 4 <= pattern.len {
			value := parse_hex_u32(pattern[i + 2..i + 4]) or { return false, u8(0), i + 4 }
			if value <= 0xff {
				return true, u8(value), i + 4
			}
			return false, u8(0), i + 4
		}
	}
	if next == `u` {
		if i + 2 < pattern.len && pattern[i + 2] == `{` {
			mut end := i + 3
			for end < pattern.len && pattern[end] != `}` {
				end++
			}
			if end < pattern.len {
				value := parse_hex_u32(pattern[i + 3..end]) or { return false, u8(0), end + 1 }
				if value <= 0xff {
					return true, u8(value), end + 1
				}
				return false, u8(0), end + 1
			}
		}
		if i + 6 > pattern.len {
			return false, u8(0), pattern.len
		}
		value := parse_hex_u32(pattern[i + 2..i + 6]) or { return false, u8(0), i + 6 }
		if value <= 0xff {
			return true, u8(value), i + 6
		}
		return false, u8(0), i + 6
	}
	if next == `U` && i + 10 <= pattern.len {
		value := parse_hex_u32(pattern[i + 2..i + 10]) or { return false, u8(0), i + 10 }
		if value <= 0xff {
			return true, u8(value), i + 10
		}
		return false, u8(0), i + 10
	}
	return true, next, i + 2
}

fn empty_byte_class() []bool {
	return []bool{len: 256}
}

fn full_byte_class() []bool {
	return []bool{len: 256, init: true}
}

fn invert_byte_class(mut set []bool) {
	for i in 0 .. set.len {
		set[i] = !set[i]
	}
}

fn add_byte_class(mut set []bool, other []bool) {
	for i, present in other {
		if present {
			set[i] = true
		}
	}
}

fn add_byte_range(mut set []bool, start u8, end u8) {
	if start <= end {
		for byte := start; byte <= end; byte++ {
			set[int(byte)] = true
		}
		return
	}
	for byte := end; byte <= start; byte++ {
		set[int(byte)] = true
	}
}

fn add_word_bytes(mut set []bool) {
	add_byte_range(mut set, `A`, `Z`)
	add_byte_range(mut set, `a`, `z`)
	add_byte_range(mut set, `0`, `9`)
	set[int(`_`)] = true
}

fn rust_property_byte_class(property string) ?[]bool {
	mut set := empty_byte_class()
	match normalize_property_name(property) {
		'any' {
			return full_byte_class()
		}
		'ascii' {
			add_byte_range(mut set, u8(0), u8(0x7f))
			return set
		}
		'decimalnumber', 'gc=nd', 'generalcategory=nd', 'nd' {
			add_byte_range(mut set, `0`, `9`)
			return set
		}
		'l', 'letter', 'alphabetic', 'alpha' {
			add_byte_range(mut set, `A`, `Z`)
			add_byte_range(mut set, `a`, `z`)
			return set
		}
		'gc=lu', 'generalcategory=lu', 'lu', 'uppercaseletter' {
			add_byte_range(mut set, `A`, `Z`)
			return set
		}
		else {
			return none
		}
	}
}

fn byte_class_to_backend_pattern(set []bool) string {
	mut any := false
	for present in set {
		if present {
			any = true
			break
		}
	}
	if !any {
		return r'(?:a^)'
	}
	mut out := []u8{cap: 64}
	out << `[`
	mut i := 0
	for i < set.len {
		if !set[i] {
			i++
			continue
		}
		start := u8(i)
		mut end := i
		for end + 1 < set.len && set[end + 1] {
			end++
		}
		append_backend_class_byte(mut out, start)
		if end > i {
			out << `-`
			append_backend_class_byte(mut out, u8(end))
		}
		i = end + 1
	}
	out << `]`
	return out.bytestr()
}

fn append_backend_class_byte(mut out []u8, byte u8) {
	match byte {
		`\\`, `]`, `-`, `^` {
			out << `\\`
			out << byte
		}
		`\n` {
			out << `\\`
			out << `n`
		}
		`\r` {
			out << `\\`
			out << `r`
		}
		`\t` {
			out << `\\`
			out << `t`
		}
		else {
			if byte < 0x20 || byte >= 0x7f {
				hex := '0123456789ABCDEF'
				out << `\\`
				out << `x`
				out << hex[int(byte >> 4)]
				out << hex[int(byte & 0x0f)]
			} else {
				out << byte
			}
		}
	}
}

fn strip_line_terminator_from_match(pattern string, config Config) !string {
	line_term := config.line_terminator or { return pattern.clone() }
	mut out := []u8{cap: pattern.len}
	mut i := 0
	mut in_class := false
	for i < pattern.len {
		byte := pattern[i]
		if byte == `[` {
			if replacement := normalize_class_without_line_term_at(pattern, i, config) {
				out << replacement.text.bytes()
				i = replacement.next
				continue
			}
			class, next := strip_class_line_terminator(pattern, i, line_term)!
			out << class.bytes()
			i = next
			continue
		}
		if byte == `]` {
			in_class = false
			out << byte
			i++
			continue
		}
		if byte == `\\` && i + 1 < pattern.len {
			next := pattern[i + 1]
			if next in [`p`, `P`] {
				if replacement := normalize_property_without_line_term_at(pattern, i, config) {
					out << replacement.text.bytes()
					i = replacement.next
					continue
				}
			}
			if next == `s` {
				if line_term_can_match_ascii_whitespace(line_term) {
					append_ascii_whitespace_class_without_line_term(mut out, line_term, true)
				} else {
					out << `\\`
					out << next
				}
				i += 2
				continue
			}
			has_byte, escaped, next_i := parse_escape_byte(pattern, i)
			if has_byte {
				if line_term_rejects_byte(line_term, escaped) {
					return Error.new(ErrorKind.not_allowed([escaped].bytestr()))
				}
			}
			for j in i .. next_i {
				out << pattern[j]
			}
			i = next_i
			continue
		}
		if !in_class && line_term_rejects_byte(line_term, byte) {
			return Error.new(ErrorKind.not_allowed([byte].bytestr()))
		}
		out << byte
		i++
	}
	return out.bytestr()
}

fn normalize_property_without_line_term_at(pattern string, start int, config Config) ?PatternReplacement {
	line_term := config.line_terminator or { return none }
	escape := rust_property_escape_at(pattern, start) or { return none }
	mut ranges := if normalize_property_name(escape.property) == 'any' {
		[UnicodeRange{rune(0), rune(0x10ffff)}]
	} else {
		encoded := rust_property_class_encoded(escape.property, config) or { return none }
		unicode_ranges_from_encoded(encoded)
	}
	if pattern[start + 1] == `P` {
		ranges = complement_unicode_ranges(ranges)
	}
	terminators := if line_term.is_crlf() {
		[UnicodeRange{`\n`, `\n`}, UnicodeRange{`\r`, `\r`}]
	} else {
		[UnicodeRange{rune(line_term.as_byte()), rune(line_term.as_byte())}]
	}
	ranges = subtract_unicode_ranges(ranges, terminators)
	if ranges.len == 0 {
		return none
	}
	return PatternReplacement{
		text: '[${ranges_backend_class_body(ranges)}]'
		next: escape.next
	}
}

fn normalize_class_without_line_term_at(pattern string, start int, config Config) ?PatternReplacement {
	line_term := config.line_terminator or { return none }
	end := find_class_end_nested(pattern, start) or { return none }
	mut ranges, ok, next := parse_unicode_class_set_expression(pattern, start + 1, end,
		config)
	if !ok || next != end {
		return none
	}
	terminators := if line_term.is_crlf() {
		[UnicodeRange{`\n`, `\n`}, UnicodeRange{`\r`, `\r`}]
	} else {
		[UnicodeRange{rune(line_term.as_byte()), rune(line_term.as_byte())}]
	}
	ranges = subtract_unicode_ranges(ranges, terminators)
	if ranges.len == 0 {
		return none
	}
	return PatternReplacement{
		text: '[${ranges_backend_class_body(ranges)}]'
		next: end + 1
	}
}

fn strip_class_line_terminator(pattern string, start int, line_term matcher.LineTerminator) !(string, int) {
	mut out := []u8{cap: pattern.len - start}
	out << `[`
	mut i := start + 1
	mut negated := false
	if i < pattern.len && pattern[i] == `^` {
		negated = true
		out << `^`
		i++
	}
	mut kept := 0
	mut excluded_line_term := false
	for i < pattern.len {
		if pattern[i] == `]` {
			if negated {
				if line_term.is_crlf() {
					if !excluded_line_term {
						out << `\\`
						out << `r`
						out << `\\`
						out << `n`
					}
				} else if !excluded_line_term {
					append_escaped_byte(mut out, line_term.as_byte())
				}
			} else if kept == 0 {
				return Error.new(ErrorKind.not_allowed(line_term.as_bytes().bytestr()))
			}
			out << `]`
			return out.bytestr(), i + 1
		}
		if pattern[i] == `\\` && i + 1 < pattern.len {
			next := pattern[i + 1]
			if next == `s` {
				if line_term_can_match_ascii_whitespace(line_term) {
					append_ascii_whitespace_class_without_line_term(mut out, line_term, false)
				} else {
					out << pattern[i]
					out << next
				}
				kept++
				i += 2
				continue
			}
			if is_byte_escape_start(next) {
				has_byte, escaped, next_i := parse_escape_byte(pattern, i)
				if has_byte && line_term_rejects_byte(line_term, escaped) {
					excluded_line_term = true
					i = next_i
					continue
				}
				for j in i .. next_i {
					out << pattern[j]
				}
				kept++
				i = next_i
				continue
			}
			if escaped := escaped_byte(next) {
				if line_term_rejects_byte(line_term, escaped) {
					excluded_line_term = true
					i += 2
					continue
				}
			}
			out << pattern[i]
			out << next
			kept++
			i += 2
			continue
		}
		if line_term_rejects_byte(line_term, pattern[i]) {
			excluded_line_term = true
			i++
			continue
		}
		out << pattern[i]
		kept++
		i++
	}
	return Error.new(ErrorKind.not_allowed(line_term.as_bytes().bytestr()))
}

fn is_byte_escape_start(byte u8) bool {
	return byte == `x` || byte == `u` || byte == `U`
}

fn line_term_can_match_ascii_whitespace(line_term matcher.LineTerminator) bool {
	if line_term.is_crlf() {
		return true
	}
	return line_term.as_byte() in [` `, `\t`, `\r`, u8(0x0b), u8(0x0c), `\n`]
}

fn append_ascii_whitespace_class_without_line_term(mut out []u8, line_term matcher.LineTerminator, wrap bool) {
	if wrap {
		out << `[`
	}
	for byte in [` `, `\t`, `\r`, u8(0x0b), u8(0x0c), `\n`] {
		if !line_term_rejects_byte(line_term, byte) {
			out << byte
		}
	}
	if wrap {
		out << `]`
	}
}

fn append_escaped_byte(mut out []u8, byte u8) {
	match byte {
		`\n` {
			out << `\\`
			out << `n`
		}
		`\r` {
			out << `\\`
			out << `r`
		}
		`\t` {
			out << `\\`
			out << `t`
		}
		else {
			out << byte
		}
	}
}

fn escaped_byte(byte u8) ?u8 {
	return match byte {
		`a` { u8(`\a`) }
		`f` { u8(`\f`) }
		`n` { u8(`\n`) }
		`r` { u8(`\r`) }
		`t` { u8(`\t`) }
		`v` { u8(`\v`) }
		else { none }
	}
}

fn line_term_rejects_byte(line_term matcher.LineTerminator, byte u8) bool {
	if line_term.is_crlf() {
		return byte == `\r` || byte == `\n`
	}
	return byte == line_term.as_byte()
}
