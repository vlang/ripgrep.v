module regex

import matcher
import regex.meta

/// Config represents the configuration of a regex matcher in this crate.
/// The configuration is itself a rough combination of the knobs found in
/// the `regex` crate itself, along with additional `grep-matcher` specific
/// options.
///
/// The configuration can be used to build a "configured" HIR expression. A
/// configured HIR expression is an HIR expression that is aware of the
/// configuration which generated it, and provides transformation on that HIR
/// such that the configuration is preserved.
pub struct Config implements IClone {
pub mut:
	case_insensitive     bool
	case_smart           bool
	multi_line           bool
	dot_matches_new_line bool
	swap_greed           bool
	ignore_whitespace    bool
	unicode              bool
	octal                bool
	size_limit           usize
	dfa_size_limit       usize
	nest_limit           u32
	line_terminator      ?matcher.LineTerminator
	ban                  ?u8
	crlf                 bool
	word                 bool
	fixed_strings        bool
	whole_line           bool
}

pub fn Config.default() Config {
	return Config{
		unicode:        true
		size_limit:     usize(100 * (1 << 20))
		dfa_size_limit: usize(1000 * (1 << 20))
		nest_limit:     u32(250)
		line_terminator: none
		ban:             none
	}
}

// V-specific: keep an explicit clone while V2 mark-used/codegen can resolve
// generated clone helpers for same-named structs across modules inconsistently.
pub fn (config Config) clone() Config {
	return Config{
		case_insensitive:     config.case_insensitive
		case_smart:           config.case_smart
		multi_line:           config.multi_line
		dot_matches_new_line: config.dot_matches_new_line
		swap_greed:           config.swap_greed
		ignore_whitespace:    config.ignore_whitespace
		unicode:              config.unicode
		octal:                config.octal
		size_limit:           config.size_limit
		dfa_size_limit:       config.dfa_size_limit
		nest_limit:           config.nest_limit
		line_terminator:      config.line_terminator
		ban:                  config.ban
		crlf:                 config.crlf
		word:                 config.word
		fixed_strings:        config.fixed_strings
		whole_line:           config.whole_line
	}
}

/// Use this configuration to build an HIR from the given patterns. The HIR
/// returned corresponds to a single regex that is an alternation of the
/// patterns given.
pub fn (config Config) build_many(patterns []string) !ConfiguredHIR {
	return ConfiguredHIR.new(config.clone(), patterns)
}

/// Accounting for the `smart_case` config knob, return true if and only if
/// this pattern should be matched case insensitively.
fn (config Config) is_case_insensitive(analysis AstAnalysis) bool {
	if config.case_insensitive {
		return true
	}
	if !config.case_smart {
		return false
	}
	return analysis.any_literal() && !analysis.any_uppercase()
}

/// Returns whether the given patterns should be treated as "fixed strings"
/// literals. This is different from just querying the `fixed_strings` knob
/// in that if the knob is false, this will still return true in some cases
/// if the patterns are themselves indistinguishable from literals.
///
/// The main idea here is that if this returns true, then it is safe
/// to build an `regex_syntax::hir::Hir` value directly from the given
/// patterns as an alternation of `hir::Literal` values.
fn (config Config) is_fixed_strings(patterns []string) bool {
	// When these are enabled, we really need to parse the patterns and
	// let them go through the standard HIR translation process in order
	// for case folding transforms to be applied.
	if config.case_insensitive || config.case_smart {
		return false
	}
	// Even if whole_line or word is enabled, both of those things can
	// be implemented by wrapping the Hir generated by an alternation of
	// fixed string literals. So for here at least, we don't care about the
	// word or whole_line settings.
	if config.fixed_strings {
		// ... but if any literal contains a line terminator, then we've
		// got to bail out because this will ultimately result in an error.
		if lineterm := config.line_terminator {
			for p in patterns {
				if has_line_terminator(lineterm, p) {
					return false
				}
			}
		}
		return true
	}
	// In this case, the only way we can hand construct the Hir is if none
	// of the patterns contain meta characters. If they do, then we need to
	// send them through the standard parsing/translation process.
	for p in patterns {
		for ch in p {
			if is_regex_meta_character(ch) {
				return false
			}
		}
		// Same deal as when fixed_strings is set above. If the pattern has
		// a line terminator anywhere, then we need to bail out and let
		// an error occur.
		if lineterm := config.line_terminator {
			if has_line_terminator(lineterm, p) {
				return false
			}
		}
	}
	return true
}

/// A "configured" HIR expression, which is aware of the configuration which
/// produced this HIR.
///
/// Since the configuration is tracked, values with this type can be
/// transformed into other HIR expressions (or regular expressions) in a way
/// that preserves the configuration. For example, the `fast_line_regex`
/// method will apply literal extraction to the inner HIR and use that to build
/// a new regex that matches the extracted literals in a way that is
/// consistent with the configuration that produced this HIR. For example, the
/// size limits set on the configured HIR will be propagated out to any
/// subsequently constructed HIR or regular expression.
pub struct ConfiguredHIR implements IClone {
	config Config
	hir    Hir
}

/// Parse the given patterns into a single HIR expression that represents
/// an alternation of the patterns given.
fn ConfiguredHIR.new(config Config, patterns []string) !ConfiguredHIR {
	mut hir := Hir.empty()
	if config.is_fixed_strings(patterns) {
		hir = Hir.from_fixed_literals(patterns)
	} else {
		mut alts := []string{cap: patterns.len}
		for p in patterns {
			if config.fixed_strings {
				alts << '(?:${escape_regex(p)})'
			} else {
				validate_rust_regex_syntax(p, config)!
				alts << '(?:${p})'
			}
		}
		mut pattern := if alts.len == 0 { '' } else { alts.join('|') }
		if config.ignore_whitespace {
			pattern = strip_ignored_whitespace(pattern)
		}
		hir = Hir.from_pattern(pattern, config)
	}
	if banned := config.ban {
		ban_check(hir.to_regex(), banned)!
	}
	if line_term := config.line_terminator {
		stripped := strip_line_terminator_from_match(hir.to_regex(), config)!
		hir = Hir.from_pattern(stripped, config)
	}
	return ConfiguredHIR{
		config: config
		hir:    hir
	}
}

/// Return a reference to the underlying configuration.
pub fn (chir &^a ConfiguredHIR) config[^a]() &^a Config {
	return &chir.config
}

/// Return a reference to the underlying HIR.
pub fn (chir &^a ConfiguredHIR) hir[^a]() &^a Hir {
	return &chir.hir
}

/// Convert this HIR to a regex that can be used for matching.
pub fn (chir ConfiguredHIR) to_regex() !meta.Regex {
	pattern := chir.backend_pattern()
	return meta.compile_with_limits(pattern, chir.config.size_limit, chir.config.dfa_size_limit) or {
		return Error.regex(err.msg())
	}
}

/// Compute the set of non-matching bytes for this HIR expression.
pub fn (chir ConfiguredHIR) non_matching_bytes() matcher.ByteSet {
	return chir.hir.non_matching_bytes()
}

/// Returns the line terminator configured on this expression.
///
/// When we have beginning/end anchors (NOT line anchors), the fast line
/// searching path isn't quite correct. Or at least, doesn't match the slow
/// path. Namely, the slow path strips line terminators while the fast path
/// does not. Since '$' (when multi-line mode is disabled) doesn't match at
/// line boundaries, the existence of a line terminator might cause it to
/// not match when it otherwise would with the line terminator stripped.
///
/// Since searching with text anchors is exceptionally rare in the context
/// of line oriented searching (multi-line mode is basically always
/// enabled), we just disable this optimization when there are text
/// anchors. We disable it by not returning a line terminator, since
/// without a line terminator, the fast search path can't be executed.
///
/// Actually, the above is no longer quite correct. Later on, another
/// optimization was added where if the line terminator was in the set of
/// bytes that was guaranteed to never be part of a match, then the higher
/// level search infrastructure assumes that the fast line-by-line search
/// path can still be taken. This optimization applies when multi-line
/// search (not multi-line mode) is enabled. In that case, there is no
/// configured line terminator since the regex is permitted to match a
/// line terminator. But if the regex is guaranteed to never match across
/// multiple lines despite multi-line search being requested, we can still
/// do the faster and more flexible line-by-line search. This is why the
/// non-matching extraction routine removes `\n` when `\A` and `\z` are
/// present even though that's not quite correct...
///
/// See: <https://github.com/BurntSushi/ripgrep/issues/2260>
pub fn (chir ConfiguredHIR) line_terminator() ?matcher.LineTerminator {
	if chir.hir.contains_haystack_anchor() {
		return none
	}
	return chir.config.line_terminator
}

/// Turns this configured HIR into an equivalent one, but where it must
/// match at the start and end of a line.
pub fn (chir ConfiguredHIR) into_whole_line() ConfiguredHIR {
	return ConfiguredHIR{
		config: chir.config.clone()
		hir:    chir.hir.into_whole_line(chir.config)
	}
}

/// Turns this configured HIR into an equivalent one, but where it must
/// match at word boundaries.
pub fn (chir ConfiguredHIR) into_word() ConfiguredHIR {
	return ConfiguredHIR{
		config: chir.config.clone()
		hir:    chir.hir.into_word(chir.config)
	}
}

fn (chir ConfiguredHIR) backend_pattern() string {
	mut flags := ''
	has_haystack_anchor := chir.hir.contains_haystack_anchor()
	pattern := normalize_backend_pattern(chir.hir.to_regex(), chir.config, has_haystack_anchor)
	analysis := AstAnalysis.from_pattern(pattern) or { AstAnalysis.new() }
	if chir.config.is_case_insensitive(analysis) {
		flags += if chir.config.unicode { 'i' } else { 'a' }
	}
	if (chir.config.multi_line || chir.config.crlf) && !has_haystack_anchor {
		flags += 'm'
	}
	if chir.config.dot_matches_new_line {
		flags += 's'
	}
	if !chir.config.unicode {
		flags += '-u'
	}
	if flags.len == 0 {
		return pattern
	}
	return '(?${flags})${pattern}'
}

struct InlineFlags {
	enabled  string
	disabled string
	next     int
	scoped   bool
}

fn inline_flags_at(pattern string, start int) ?InlineFlags {
	if start + 3 >= pattern.len || pattern[start] != `(` || pattern[start + 1] != `?` {
		return none
	}
	mut i := start + 2
	mut enabled := []u8{}
	mut disabled := []u8{}
	mut disabling := false
	mut saw_flag := false
	for i < pattern.len && pattern[i] !in [`:`, `)`] {
		if pattern[i] == `-` {
			if disabling {
				return none
			}
			disabling = true
			i++
			continue
		}
		if pattern[i] !in [`i`, `m`, `s`, `U`, `u`, `x`, `R`] {
			return none
		}
		saw_flag = true
		if disabling {
			disabled << pattern[i]
		} else {
			enabled << pattern[i]
		}
		i++
	}
	if !saw_flag || i >= pattern.len {
		return none
	}
	return InlineFlags{
		enabled:  enabled.bytestr()
		disabled: disabled.bytestr()
		next:     i + 1
		scoped:   pattern[i] == `:`
	}
}

fn apply_inline_flags(flags InlineFlags, config Config) Config {
	mut next := config
	for flag in flags.enabled.bytes() {
		match flag {
			`U` { next.swap_greed = true }
			`u` { next.unicode = true }
			`x` { next.ignore_whitespace = true }
			`R` { next.crlf = true }
			else {}
		}
	}
	for flag in flags.disabled.bytes() {
		match flag {
			`U` { next.swap_greed = false }
			`u` { next.unicode = false }
			`x` { next.ignore_whitespace = false }
			`R` { next.crlf = false }
			else {}
		}
	}
	return next
}

fn backend_inline_flags(flags InlineFlags, unicode bool) string {
	mut enabled := []u8{}
	mut disabled := []u8{}
	for flag in flags.enabled.bytes() {
		match flag {
			`i` { enabled << if unicode { `i` } else { `a` } }
			`m`, `s`, `u` { enabled << flag }
			else {}
		}
	}
	for flag in flags.disabled.bytes() {
		match flag {
			`i` { disabled << `i` }
			`m`, `s`, `u` { disabled << flag }
			else {}
		}
	}
	mut out := enabled.bytestr()
	if disabled.len > 0 {
		out += '-${disabled.bytestr()}'
	}
	return out
}

fn normalize_backend_pattern(pattern string, config Config, explicit_line_anchors bool) string {
	mut out := []u8{cap: pattern.len}
	mut i := 0
	mut in_class := false
	mut escaped := false
	mut effective_config := config
	for i < pattern.len {
		ch := pattern[i]
		if !escaped && !in_class {
			if flags := inline_flags_at(pattern, i) {
				next_config := apply_inline_flags(flags, effective_config)
				backend_flags := backend_inline_flags(flags, next_config.unicode)
				if flags.scoped {
					if end := matching_group_end(pattern, i) {
						out << if backend_flags == '' { '(?:'.bytes() } else { '(?${backend_flags}:'.bytes() }
						out << normalize_backend_pattern(pattern[flags.next..int(end)], next_config,
							explicit_line_anchors).bytes()
						out << `)`
						i = int(end) + 1
						escaped = false
						continue
					}
				} else {
					effective_config = next_config
					if backend_flags != '' {
						out << '(?${backend_flags})'.bytes()
					}
					i = flags.next
					escaped = false
					continue
				}
			}
		}
		if !escaped && !in_class && ch == `[` {
			if replacement := normalize_unicode_class_at(pattern, i, effective_config) {
				out << replacement.text.bytes()
				i = replacement.next
				escaped = false
				continue
			}
			if replacement := normalize_posix_alpha_class_at(pattern, i, effective_config) {
				out << replacement.text.bytes()
				i = replacement.next
				escaped = false
				continue
			}
			if replacement := normalize_class_set_operation_at(pattern, i, effective_config) {
				out << replacement.text.bytes()
				i = replacement.next
				escaped = false
				continue
			}
			if replacement := normalize_property_class_at(pattern, i, effective_config) {
				out << replacement.text.bytes()
				i = replacement.next
				escaped = false
				continue
			}
		}
		if effective_config.ignore_whitespace && !escaped && !in_class && ch == `#` {
			for i < pattern.len && pattern[i] != `\n` {
				i++
			}
			escaped = false
			continue
		}
		if effective_config.ignore_whitespace && !escaped && !in_class && is_extended_whitespace(ch) {
			i++
			escaped = false
			continue
		}
		if explicit_line_anchors && (effective_config.multi_line || effective_config.crlf) && !escaped && !in_class
			&& ch == `^` {
			out << r'(?m:^)'.bytes()
			i++
			escaped = false
			continue
		}
		if explicit_line_anchors && (effective_config.multi_line || effective_config.crlf) && !escaped && !in_class
			&& ch == `$` {
			if effective_config.crlf {
				out << r'\x0D?(?m:$)'.bytes()
			} else {
				out << r'(?m:$)'.bytes()
			}
			i++
			escaped = false
			continue
		}
		if effective_config.crlf && !escaped && !in_class && ch == `$` {
			out << r'\x0D?$'.bytes()
			i++
			continue
		}
		if !escaped && !in_class && i + 3 < pattern.len && ch == `(` && pattern[i + 1] == `?`
			&& pattern[i + 2] == `<` && pattern[i + 3] != `=` && pattern[i + 3] != `!` {
			out << '(?P<'.bytes()
			i += 3
			escaped = false
			continue
		}
		if !escaped && ch == `[` {
			in_class = true
		} else if !escaped && ch == `]` {
			in_class = false
		}
		if !escaped && !in_class && ch == `\\` {
			if variant := rust_word_boundary_variant_at(pattern, i) {
				out << backend_word_boundary(variant.kind, effective_config.unicode).bytes()
				i = variant.next
				escaped = false
				continue
			}
			if i + 1 < pattern.len {
				next := pattern[i + 1]
				match next {
					`A` {
						out << r'\A'.bytes()
						i += 2
						escaped = false
						continue
					}
					`z` {
						out << r'\z'.bytes()
						i += 2
						escaped = false
						continue
					}
					`<`, `>` {
						kind := if next == `<` { 'start' } else { 'end' }
						out << backend_word_boundary(kind, effective_config.unicode).bytes()
						i += 2
						escaped = false
						continue
					}
					`b`, `B` {
						kind := if next == `b` { 'boundary' } else { 'negate' }
						out << backend_word_boundary(kind, effective_config.unicode).bytes()
						i += 2
						escaped = false
						continue
					}
					`x`, `u`, `U` {
						if escape := rust_unicode_escape_at(pattern, i) {
							if escape.codepoint <= 0xff {
								out << '\\x${escape.codepoint:02x}'.bytes()
							} else {
								out << rune(escape.codepoint).str().bytes()
							}
							i = escape.next
							escaped = false
							continue
						}
					}
					`d` {
						out << digit_backend_class(effective_config).bytes()
						i += 2
						escaped = false
						continue
					}
					`D` {
						out << negated_backend_class(digit_backend_class_body(effective_config),
							effective_config).bytes()
						i += 2
						escaped = false
						continue
					}
					`s` {
						out << whitespace_backend_class(effective_config).bytes()
						i += 2
						escaped = false
						continue
					}
					`S` {
						out << negated_backend_class(whitespace_backend_class_body(effective_config),
							effective_config).bytes()
						i += 2
						escaped = false
						continue
					}
					`w` {
						out << word_backend_class(effective_config).bytes()
						i += 2
						escaped = false
						continue
					}
					`W` {
						out << negated_backend_class(word_backend_class_body(effective_config),
							effective_config).bytes()
						i += 2
						escaped = false
						continue
					}
					`p`, `P` {
						if property_escape := rust_property_escape_at(pattern, i) {
							if next == `p` {
								if replacement := rust_property_replacement(property_escape.property,
									effective_config) {
									out << replacement.bytes()
									i = property_escape.next
									escaped = false
									continue
								}
							} else {
								if normalize_property_name(property_escape.property) == 'any' {
									out << r'(?:a^)'.bytes()
									i = property_escape.next
									escaped = false
									continue
								}
								if body := rust_property_class_body(property_escape.property,
									effective_config) {
									out << negated_backend_class(body, effective_config).bytes()
									i = property_escape.next
									escaped = false
									continue
								}
							}
						}
					}
					else {}
				}
			}
		}
		if !escaped && !in_class && effective_config.swap_greed
			&& is_standalone_single_quantifier(pattern, i) {
			out << ch
			if i + 1 < pattern.len && pattern[i + 1] in [`?`, `+`] {
				if pattern[i + 1] == `+` {
					out << `?`
				}
				i += 2
			} else {
				out << `?`
				i++
			}
			escaped = false
			continue
		}
		if !escaped && !in_class && is_possessive_single_quantifier(pattern, i) {
			out << ch
			i += 2
			escaped = false
			continue
		}
		if !escaped && !in_class && ch == `{` {
			if effective_config.swap_greed {
				if end := braced_quantifier_end(pattern, i) {
					out << pattern[i..int(end) + 1].bytes()
					if int(end) + 1 < pattern.len && pattern[int(end) + 1] in [`?`, `+`] {
						if pattern[int(end) + 1] == `+` {
							out << `?`
						}
						i = int(end) + 2
					} else {
						out << `?`
						i = int(end) + 1
					}
					escaped = false
					continue
				}
			}
			if end := possessive_braced_quantifier_end(pattern, i) {
				out << pattern[i..int(end) + 1].bytes()
				i = int(end) + 2
				escaped = false
				continue
			}
		}
		out << ch
		escaped = !escaped && ch == `\\`
		i++
	}
	return out.bytestr()
}

struct RustBracedHexEscape {
	codepoint u32
	next      int
}

fn rust_braced_hex_escape_at(pattern string, i int) ?RustBracedHexEscape {
	if i + 3 >= pattern.len || pattern[i..i + 3] != r'\x{' {
		return none
	}
	mut end := i + 3
	for end < pattern.len && pattern[end] != `}` {
		end++
	}
	if end >= pattern.len || end == i + 3 {
		return none
	}
	codepoint := parse_hex_u32(pattern[i + 3..end]) or { return none }
	if codepoint > 0x10ffff || (codepoint >= 0xd800 && codepoint <= 0xdfff) {
		return none
	}
	return RustBracedHexEscape{
		codepoint: codepoint
		next:      end + 1
	}
}

fn rust_unicode_escape_at(pattern string, i int) ?RustBracedHexEscape {
	if escape := rust_braced_hex_escape_at(pattern, i) {
		return escape
	}
	if i + 2 >= pattern.len || pattern[i] != `\\` || pattern[i + 1] !in [`u`, `U`] {
		return none
	}
	if pattern[i + 1] == `u` && pattern[i + 2] == `{` {
		mut end := i + 3
		for end < pattern.len && pattern[end] != `}` {
			end++
		}
		if end >= pattern.len || end == i + 3 {
			return none
		}
		codepoint := parse_hex_u32(pattern[i + 3..end]) or { return none }
		if !is_valid_unicode_escape_codepoint(codepoint) {
			return none
		}
		return RustBracedHexEscape{
			codepoint: codepoint
			next:      end + 1
		}
	}
	digits := if pattern[i + 1] == `u` { 4 } else { 8 }
	if i + 2 + digits > pattern.len {
		return none
	}
	codepoint := parse_hex_u32(pattern[i + 2..i + 2 + digits]) or { return none }
	if !is_valid_unicode_escape_codepoint(codepoint) {
		return none
	}
	return RustBracedHexEscape{
		codepoint: codepoint
		next:      i + 2 + digits
	}
}

fn is_valid_unicode_escape_codepoint(codepoint u32) bool {
	return codepoint <= 0x10ffff && !(codepoint >= 0xd800 && codepoint <= 0xdfff)
}

fn matching_group_end(pattern string, start int) ?usize {
	mut depth := 0
	mut escaped := false
	mut in_class := false
	for i := start; i < pattern.len; i++ {
		ch := pattern[i]
		if escaped {
			escaped = false
			continue
		}
		if ch == `\\` {
			escaped = true
			continue
		}
		if in_class {
			if ch == `]` {
				in_class = false
			}
			continue
		}
		if ch == `[` {
			in_class = true
			continue
		}
		if ch == `(` {
			depth++
			continue
		}
		if ch == `)` {
			depth--
			if depth == 0 {
				return usize(i)
			}
		}
	}
	return none
}

struct RustWordBoundaryVariant {
	kind string
	next int
}

fn rust_word_boundary_variant_at(pattern string, i int) ?RustWordBoundaryVariant {
	variants := {
		r'\b{start}':      'start'
		r'\b{end}':        'end'
		r'\b{start-half}': 'start-half'
		r'\b{end-half}':   'end-half'
	}
	for variant, kind in variants {
		if i + variant.len <= pattern.len && pattern[i..i + variant.len] == variant {
			return RustWordBoundaryVariant{
				kind: kind.to_owned()
				next: i + variant.len
			}
		}
	}
	return none
}

fn backend_word_boundary(kind string, unicode bool) string {
	mode := if unicode { 'unicode' } else { 'ascii' }
	return '\\b{${kind}-${mode}}'
}

fn rust_property_escape_end(pattern string, i int) ?usize {
	if i + 3 >= pattern.len || pattern[i] != `\\` || (pattern[i + 1] != `p`
		&& pattern[i + 1] != `P`) || pattern[i + 2] != `{` {
		return none
	}
	mut end := i + 3
	for end < pattern.len && pattern[end] != `}` {
		end++
	}
	if end >= pattern.len {
		return none
	}
	return usize(end + 1)
}

struct RustPropertyEscape {
	property string
	next     int
}

fn rust_property_escape_at(pattern string, i int) ?RustPropertyEscape {
	if i + 2 >= pattern.len || pattern[i] != `\\` || (pattern[i + 1] != `p`
		&& pattern[i + 1] != `P`) {
		return none
	}
	if end := rust_property_escape_end(pattern, i) {
		return RustPropertyEscape{
			property: pattern[i + 3..int(end) - 1].to_owned()
			next:     int(end)
		}
	}
	next := pattern[i + 2]
	if is_ascii_property_letter(next) {
		return RustPropertyEscape{
			property: next.ascii_str().to_owned()
			next:     i + 3
		}
	}
	return none
}

fn is_ascii_property_letter(byte u8) bool {
	return (byte >= `A` && byte <= `Z`) || (byte >= `a` && byte <= `z`)
}

fn rust_property_replacement(property string, config Config) ?string {
	normalized := normalize_property_name(property)
	if normalized == 'any' {
		return '(?:.|\n|\r)'
	}
	if normalized == 'ascii' {
		return ascii_backend_class()
	}
	if body := rust_property_class_body(property, config) {
		return '[${body}]'
	}
	return none
}

fn rust_property_class_body(property string, config Config) ?string {
	encoded := rust_property_class_encoded(property, config) or { return none }
	return generated_unicode_range_body(encoded)
}

fn rust_property_class_encoded(property string, config Config) ?string {
	_ = config
	normalized := normalize_property_name(property)
	if key := generated_unicode_binary_property_key(normalized) {
		return generated_unicode_property_encoded(key)
	}
	if !normalized.contains('=') {
		return none
	}
	property_name := normalized.all_before('=')
	property_value := normalized.all_after('=')
	canonical_property := generated_unicode_property_name(property_name) or { return none }
	canonical_value := generated_unicode_property_value(canonical_property, property_value) or {
		return none
	}
	table := match canonical_property {
		'Age' { 'age' }
		'General_Category' { 'gc' }
		'Script' { 'script' }
		'Script_Extensions' { 'scx' }
		'Grapheme_Cluster_Break' { 'gcb' }
		'Sentence_Break' { 'sb' }
		'Word_Break' { 'wb' }
		else { return none }
	}
	return generated_unicode_property_encoded('${table}=${canonical_value}')
}

fn normalize_property_name(property string) string {
	mut out := []u8{cap: property.len}
	for byte in property.to_lower().bytes() {
		if byte == `_` || byte == `-` || byte == ` ` {
			continue
		}
		if byte == `:` {
			out << `=`
			continue
		}
		out << byte
	}
	return out.bytestr()
}

fn rust_property_is_supported(property string, config Config) bool {
	normalized := normalize_property_name(property)
	if normalized == 'any' {
		return true
	}
	return rust_property_class_body(property, config) != none
}

